// Піни дисплея
#define SCE  PB0  // Chip Enable (CS)
#define RST  PB1  // Reset
#define DC   PB2  // Data/Command
#define SCLK PB5  // Clock
#define MOSI PB3  // Data In (MOSI)

// Прототипи функцій
void Gotoxy(int x, int y);
void Write_lcd(uint8_t dc, uint8_t data);

// Ініціалізація LCD
void Lcd_Init(void) {
    // Настроюємо порти для пінів дисплея як виходи
    DDRB |= (1 << SCE) | (1 << RST) | (1 << DC) | (1 << SCLK) | (1 << MOSI);
}

// Ініціалізація SPI для AVR
void SPI_init(void) {
    // Налаштування MOSI, SCLK, і SS як виходи
    DDRB |= (1 << MOSI) | (1 << SCLK) | (1 << SCE);  // SCE як SS
    // Встановлюємо SPI в режим Master
    SPCR = (1 << SPE) | (1 << MSTR) | (1 << SPR0);  // SPE - SPI Enable, MSTR - Master, SPR0 - швидкість SPI
}

// Очищення LCD
void Lcd_Clear(void) {
    uint8_t i, j;
    // Відправка команди на очищення екрану
    for (i = 0; i < 6; i++) {  // 6 сторінок на дисплеї (6 рядків)
        Gotoxy(0, i);  // Переміщення на початок кожної сторінки
        for (j = 0; j < 84; j++) {  // 84 пікселя по горизонталі
            Write_lcd(DC, 0x00);  // Записуємо нуль (піксель вимкнений)
        }
    }
}

// Переміщення курсора на дисплеї
void Gotoxy(int x, int y) {
    // Позиціюємо дисплей на потрібну сторінку (0..5)
    Write_lcd(0, 0xB0 + y);  // Команда для вибору сторінки
    // Позиціюємо курсор по горизонталі
    Write_lcd(0, 0x00 + (x & 0x0F));  // Мала частина адреси
    Write_lcd(0, 0x10 + ((x >> 4) & 0x0F));  // Велика частина адреси
}

// Написання символу на LCD
void Write_lcd(uint8_t dc, uint8_t data) {
    if (dc) {
        // Якщо dc = 1, це дані (символи)
        PORTB |= (1 << DC);  // Встановлюємо DC в 1 (Data)
    } else {
        // Якщо dc = 0, це команда
        PORTB &= ~(1 << DC);  // Встановлюємо DC в 0 (Command)
    }

    // Відправка даних через SPI
    SPDR = data;  // Завантажуємо дані в регістр даних SPI
    while (!(SPSR & (1 << SPIF)));  // Чекаємо завершення передачі
}

